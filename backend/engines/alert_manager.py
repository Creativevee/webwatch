from datetime import datetime, timedelta
from ipaddress import ip_address

import requests

from config import settings
import models
import schemas
from routers.ws import manager as ws_manager


def broadcastAlert(alert):
    alertData = schemas.AlertRead.model_validate(alert).model_dump(mode="json")
    ws_manager.broadcast_sync(alertData)


def createAlert(
    db,
    message,
    severity,
    ruleId=None,
    logSourceId=None,
    ipAddress=None,
    mitreTechnique=None,
):
    alert = models.Alert(
        rule_id=ruleId,
        log_source_id=logSourceId,
        ip_address=ipAddress,
        message=message,
        severity=severity,
        mitre_technique=mitreTechnique,
        is_resolved=False,
    )
    db.add(alert)
    db.commit()
    db.refresh(alert)

    broadcastAlert(alert)
    return alert


def checkAbuseIpdb(ipAddress):
    headers = {"Key": settings.abuseipdb_api_key, "Accept": "application/json"}
    params = {"ipAddress": ipAddress, "maxAgeInDays": 90}

    response = requests.get(
        "https://api.abuseipdb.com/api/v2/check",
        headers=headers,
        params=params,
        timeout=10,
    )
    response.raise_for_status()

    data = response.json()["data"]
    return {
        "abuseConfidenceScore": data["abuseConfidenceScore"],
        "countryCode": data.get("countryCode"),
        "totalReports": data["totalReports"],
    }


def getCachedReputation(ipAddress, db):
    record = db.query(models.IPReputationCache).filter_by(ip_address=ipAddress).first()

    realCheck = (
        record
        and record.country_code is not None
        and record.last_checked
        and (datetime.utcnow() - record.last_checked) < timedelta(hours=24)
    )
    if realCheck:
        return record

    reputation = checkAbuseIpdb(ipAddress)

    if record is None:
        record = models.IPReputationCache(ip_address=ipAddress)
        db.add(record)

    record.abuse_confidence_score = reputation["abuseConfidenceScore"]
    record.country_code = reputation["countryCode"]
    record.is_malicious = reputation["abuseConfidenceScore"] >= 50
    record.last_checked = datetime.utcnow()

    db.commit()
    db.refresh(record)
    return record


ALERT_SYSTEM_PROMPT = (
    "You are a security analyst assistant helping a junior engineer understand "
    "automated security alerts.\n\n"
    "Your task is to explain, in simple plain English, what the security alert "
    "means and why it may be important.\n\n"
    "You will be given the exact text of one alert generated by an automated "
    "detection rule. Base your explanation only on the information contained in "
    "the alert. Do not invent or assume information that is not present. Do not "
    "speculate about the attacker's identity, motive, or whether the attack was "
    "successful. Do not claim that data was stolen, a system was compromised, "
    "or any other outcome occurred unless the alert explicitly states this. "
    "If the alert does not provide enough information to determine something, "
    "do not make a conclusion about it.\n\n"
    "Explain the alert rather than repeating the raw alert text. Keep the "
    "explanation to 2-3 short sentences. Use simple English that a junior "
    "engineer can understand. Avoid unnecessary technical jargon and do not "
    "use bullet points."
)


def alertOpenAi(message):
    from openai import OpenAI

    client = OpenAI(api_key=settings.openai_api_key)

    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {"role": "system", "content": ALERT_SYSTEM_PROMPT},
            {"role": "user", "content": message},
        ],
    )

    return response.choices[0].message.content


def alertFinding(
    db,
    message,
    severity,
    mitreTechnique=None,
    ruleId=None,
    logSourceId=None,
    ipAddress=None,
):
    alert = createAlert(
        db,
        message=message,
        severity=severity,
        ruleId=ruleId,
        logSourceId=logSourceId,
        ipAddress=ipAddress,
        mitreTechnique=mitreTechnique,
    )

    if ipAddress and not ip_address(ipAddress).is_private:
        try:
            reputation = getCachedReputation(ipAddress, db)
            alert.abuseipdb_score = reputation.abuse_confidence_score
        except Exception as e:
            print(f"AbuseIPDB lookup failed for {ipAddress}: {e}")

    try:
        alert.ai_explanation = alertOpenAi(message)
    except Exception as e:
        print(f"AI explanation failed: {e}")

    db.commit()
    db.refresh(alert)
    broadcastAlert(alert)

    return alert
