from datetime import datetime, timedelta

import requests

from config import settings
import models


def createAlert(
    db,
    message,
    severity,
    ruleId=None,
    logSourceId=None,
    ipAddress=None,
    mitreTechnique=None,
    abuseipdbScore=None,
    aiExplanation=None,
):
    alert = models.Alert(
        rule_id=ruleId,
        log_source_id=logSourceId,
        ip_address=ipAddress,
        message=message,
        severity=severity,
        mitre_technique=mitreTechnique,
        abuseipdb_score=abuseipdbScore,
        ai_explanation=aiExplanation,
        is_resolved=False,
    )
    db.add(alert)
    db.commit()
    return alert


def checkAbuseIpdb(ipAddress):
    headers = {"Key": settings.abuseipdb_api_key, "Accept": "application/json"}
    params = {"ipAddress": ipAddress, "maxAgeInDays": 90}

    response = requests.get(
        "https://api.abuseipdb.com/api/v2/check", headers=headers, params=params
    )
    response.raise_for_status()

    data = response.json()["data"]
    return {
        "abuseConfidenceScore": data["abuseConfidenceScore"],
        "countryCode": data.get("countryCode"),
        "totalReports": data["totalReports"],
    }


def getCachedReputation(ipAddress, db):
    record = db.query(models.IPReputationCache).filter_by(ip_address=ipAddress).first()

    realCheck = (
        record
        and record.country_code is not None
        and record.last_checked
        and (datetime.utcnow() - record.last_checked) < timedelta(hours=24)
    )
    if realCheck:
        return record

    reputation = checkAbuseIpdb(ipAddress)

    if record is None:
        record = models.IPReputationCache(ip_address=ipAddress)
        db.add(record)

    record.abuse_confidence_score = reputation["abuseConfidenceScore"]
    record.country_code = reputation["countryCode"]
    record.is_malicious = reputation["abuseConfidenceScore"] >= 50
    record.last_checked = datetime.utcnow()

    db.commit()
    db.refresh(record)
    return record


ALERT_SYSTEM_PROMPT = (
    "You are a security analyst assistant helping a junior engineer understand automated "
    "security alerts.\n\n"
    "Your task is to explain, in plain English, what a given security alert means and why "
    "it could matter.\n\n"
    "You will be given the exact text of one alert generated by an automated detection rule. "
    "Base your explanation strictly on the information contained in that alert text. Do not "
    "invent details that aren't present, do not speculate about the attacker's identity, "
    "motive, or whether the attack succeeded, and do not claim any outcome (such as data being "
    "stolen or a system being compromised) unless it is explicitly stated in the alert. If "
    "something isn't mentioned in the alert, simply don't mention it either.\n\n"
    "Respond in 2-3 short sentences of plain English, with no technical jargon and no bullet "
    "points. Do not just repeat the raw alert text back - explain what it actually means."
)


def alertOpenAi(message):
    from openai import OpenAI

    client = OpenAI(api_key=settings.openai_api_key)

    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {"role": "system", "content": ALERT_SYSTEM_PROMPT},
            {"role": "user", "content": message},
        ],
    )

    return response.choices[0].message.content


def alertOllama(message):
    payload = {
        "model": settings.ollama_model,
        "messages": [
            {"role": "system", "content": ALERT_SYSTEM_PROMPT},
            {"role": "user", "content": message},
        ],
        "stream": False,
    }

    response = requests.post(f"{settings.ollama_host}/api/chat", json=payload)
    response.raise_for_status()

    return response.json()["message"]["content"]


def receiveFinding(
    db,
    message,
    severity,
    mitreTechnique=None,
    ruleId=None,
    logSourceId=None,
    ipAddress=None,
):
    # Step 1: AbuseIPDB reputation lookup (only if we actually have an IP to check)
    abuseipdbScore = None
    if ipAddress:
        try:
            reputation = getCachedReputation(ipAddress, db)
            abuseipdbScore = reputation.abuse_confidence_score
        except Exception as e:
            print(f"AbuseIPDB lookup failed for {ipAddress}: {e}")

    # Step 2: MITRE tag - passed straight through from whichever rule/detection triggered this

    # Step 3: AI-generated plain-English explanation
    aiExplanation = None
    try:
        aiExplanation = alertOllama(message)
    except Exception as e:
        print(f"AI explanation failed: {e}")

    # Step 4: save everything to the database, even if enrichment above partially failed
    return createAlert(
        db,
        message=message,
        severity=severity,
        ruleId=ruleId,
        logSourceId=logSourceId,
        ipAddress=ipAddress,
        mitreTechnique=mitreTechnique,
        abuseipdbScore=abuseipdbScore,
        aiExplanation=aiExplanation,
    )
